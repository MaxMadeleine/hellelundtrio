/** Press downloads are capped here: enough for print, small enough to serve. */
const PRESS_MAX_WIDTH = 3000

async function emitDerivative(d: Derivative) {
  const image = sharp(d.source, { failOn: 'none' })
  const { width: sourceWidth = 0, height: sourceHeight = 0 } = await image.metadata()
  const widths = [...new Set(d.widths.map((w) => Math.min(w, sourceWidth)))].sort((a, b) => a - b)

  for (const width of widths) {
    const resized = sharp(d.source, { failOn: 'none' }).resize({
      width,
      height: d.square ? width : undefined,
      fit: d.square ? 'contain' : 'inside',
      background: { r: 13, g: 13, b: 15 },
      withoutEnlargement: true,
    })

    await Promise.all([
      resized.clone().avif({ quality: 62, effort: 4 }).toFile(`${OUT}/${d.name}-${width}.avif`),
      resized.clone().webp({ quality: 78 }).toFile(`${OUT}/${d.name}-${width}.webp`),
      resized
        .clone()
        .jpeg({ quality: 80, mozjpeg: true })
        .toFile(`${OUT}/${d.name}-${width}.jpg`),
    ])
  }

  const aspectRatio = d.square ? 1 : sourceWidth / sourceHeight
  return { name: d.name, widths, aspectRatio: Number(aspectRatio.toFixed(4)) }
}

async function emitPress(p: { name: string; source: string }) {
  await sharp(p.source, { failOn: 'none' })
    .resize({ width: PRESS_MAX_WIDTH, withoutEnlargement: true })
    .jpeg({ quality: 90, mozjpeg: true })
    .toFile(`${PRESS_OUT}/${p.name}.jpg`)
}

/**
 * Open Graph card. Cropped off-centre so Helle stays in frame at 1.91:1,
 * which crops hard into a 1771x1512 source.
 */
async function emitOpenGraph() {
  await sharp(`${ARCHIVE}/assets/helle-lund_1.jpg`, { failOn: 'none' })
    .resize(1200, 630, { fit: 'cover', position: 'right top' })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile('public/og.jpg')
}

async function main() {
  await rm(OUT, { recursive: true, force: true })
  await rm(PRESS_OUT, { recursive: true, force: true })
  await mkdir(OUT, { recursive: true })
  await mkdir(PRESS_OUT, { recursive: true })

  const manifest = []
  for (const d of DERIVATIVES) {
    manifest.push(await emitDerivative(d))
    console.log(`image  ${d.name}`)
  }

  for (const p of PRESS) {
    await emitPress(p)
    console.log(`press  ${p.name}`)
  }

  await emitOpenGraph()
  console.log('image  og')

  const header = [
    '// Generated by `pnpm images`. Do not edit by hand.',
    '',
    'export type ImageAsset = {',
    '  name: string',
    '  widths: number[]',
    '  aspectRatio: number',
    '}',
    '',
  ].join('\n')

  const body = `export const images = ${JSON.stringify(
    Object.fromEntries(manifest.map((m) => [m.name, m])),
    null,
    2,
  )} as const satisfies Record<string, ImageAsset>\n\nexport type ImageName = keyof typeof images\n`

  await writeFile(path.join('src', 'images.generated.ts'), header + body)
  console.log('wrote  src/images.generated.ts')
}

main().catch((error: unknown) => {
  console.error(error)
  process.exit(1)
})
